"""`repolens featuretrace propose`: draft FeatureTrace markers from the evidence graph.

    repolens featuretrace propose              write a proposal under .repolens/featuretrace-proposal
    repolens featuretrace propose --jsdoc      also draft fact-only JSDoc for route handlers and data access
    repolens featuretrace propose --function-lens  also draft stable, comment-only function ids
    repolens featuretrace propose --owners     also draft canonical_owners.draft.yaml (never written into the tree)
    repolens featuretrace propose --apply      write the saved, reviewed proposal into the repository

A marker records what a person decided a feature is. This command only drafts one from
static evidence: the route, call and store edges that `impact.features` groups by route
segment. Every role ends in "(draft)" and every tag is a route segment until someone renames
it (`--tag orders=order-management`). Each draft is checked with the audit's own rules and
any issue it predicts is listed in proposal.json (`audit_issues`); passing the audit says the
references are well formed, not that the declared flow is what the feature does.

Drafting writes only to the proposal directory, and refuses to replace a file there that it
did not write. `--apply` does not draft again: it writes the proposal.json saved by the
drafting run, whose patch you reviewed. It refuses to run when there is no saved proposal,
it was drafted for another root, the patch no longer matches it, or its analysis was
incomplete. It skips (and lists) a file whose bytes changed since the draft, a path that
resolves outside the root, and, without `--allow-dirty`, a file git does not hold a clean
committed copy of, or every file when the root is not a git checkout.

Exit codes: 2 when the analysis fails or is incomplete (the proposal is still written), when
the output directory holds files this command did not write, or when `--apply` refuses to
run; 1 when `--apply` skipped a file; 0 otherwise.
"""
